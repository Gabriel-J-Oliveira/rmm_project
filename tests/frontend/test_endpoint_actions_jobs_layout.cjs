const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..','..');
const html=fs.readFileSync(path.join(root,'templates/dashboard/endpoint_detail.html'),'utf8');
const css=fs.readFileSync(path.join(root,'static/css/endpoint_actions_jobs.css'),'utf8');
const recovery=fs.readFileSync(path.join(root,'static/js/endpoint_winrm_recovery.js'),'utf8');
const approved=fs.readFileSync(path.join(root,'static/js/endpoint_approved_scripts.js'),'utf8');
const start=html.indexOf('data-endpoint-tab-panel="tasks"');
const end=html.indexOf('data-endpoint-tab-panel="diagnostics"',start);
assert(start>=0&&end>start,'actions tab is a stable template subtree');
const actions=html.slice(start,end);
assert(actions.includes('endpoint-actions-jobs-layout'));
assert(actions.includes('data-endpoint-actions-core'));
assert(actions.includes('data-endpoint-actions-maintenance'));
assert(actions.includes('data-endpoint-actions-critical'));
assert(actions.includes('data-approved-scripts-placement'));
assert(actions.includes('data-endpoint-jobs-scroll'));
assert(actions.includes('data-winrm-check'));
assert(actions.includes('data-winrm-recovery-open'));
assert(!html.includes('Voltar para endpoints'));
assert(!actions.includes('<details class="endpoint-action-category'),'action categories do not collapse');
assert(!actions.includes('<summary>Estado local reportado'),'local WinRM state is always visible');
assert(!actions.includes('<details class="endpoint-winrm-local-details'),'local WinRM state is not a dropdown');
assert(!html.slice(0,start).includes('Diagnóstico e recuperação WinRM'),'WinRM is not a floating card above the tabs');
assert.match(css,/grid-template-columns:\s*minmax\(0,\s*4fr\)\s+minmax\(260px,\s*1fr\)/,'desktop layout uses 4:1 columns');
assert.match(css,/\.endpoint-actions-jobs-layout\s*\{[^}]*align-items:\s*stretch/,'jobs panel stretches to the actions column');
assert.doesNotMatch(css,/\.endpoint-jobs-panel\s*\{[^}]*?(?:^|[;\s])height\s*:/,'jobs panel has no fixed height');
assert.match(css,/\.endpoint-jobs-scroll[\s\S]*?overflow-y:\s*auto/,'job scrolling is isolated to its list');
assert.match(css,/@media\s*\(max-width:\s*1050px\)[\s\S]*?grid-template-columns:\s*minmax\(0,\s*1fr\)/,'layout stacks when the 4:1 split no longer fits');
assert.match(css,/endpoint-quick-action-button:hover:not\(:disabled\)[\s\S]*?background:\s*rgba\(124,\s*58,\s*237/,'interactive hover uses NightOwl purple');
assert.match(css,/endpoint-actions-tab \.panel:hover[\s\S]*?box-shadow:\s*none/,'panel hover has no elevation');
assert.doesNotMatch(recovery,/MutationObserver/,'WinRM recovery mounts directly into stable markup');
assert.doesNotMatch(approved,/MutationObserver/,'approved scripts do not remount from mutations');
assert.match(actions,/data-terminal-open/,'terminal action is reserved in quick actions');
console.log('endpoint actions/jobs layout: stable slots, integrated WinRM and bounded 4:1 layout OK');
